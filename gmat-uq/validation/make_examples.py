"""Write the configuration files in ``examples/`` from the validation cases.

The examples are generated, not typed, so that their numbers are exactly the
ones the validation campaign uses::

    python validation/make_examples.py --gmat-root C:/path/to/GMAT

Without GMAT only the two-body example is written.
"""

from __future__ import annotations

import argparse
import os
import shutil
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import cases  # noqa: E402

EXAMPLES = Path(__file__).resolve().parent.parent / "examples"


def _numbers(values) -> str:
    return "[" + ", ".join(repr(float(value)) for value in values) + "]"


def _error_model(name: str, model) -> list[str]:
    return [
        f"[error_models.{name}]",
        f"fixed_magnitude_sigma = {model.fixed_magnitude_sigma!r}            # km/s",
        f"proportional_magnitude_sigma = {model.proportional_magnitude_sigma!r}     # fraction",
        f"fixed_pointing_sigma = {model.fixed_pointing_sigma!r}             # km/s per axis",
        f"proportional_pointing_sigma = {model.proportional_pointing_sigma!r}      # rad per axis",
        "",
    ]


def _maneuver(maneuver, error_model: str | None, navigation: str | None, target: str | None) -> list[str]:
    lines = ["[[maneuver]]", f'name = "{maneuver.name}"', f"time = {maneuver.time!r}"]
    if any(maneuver.dv):
        lines.append(f"dv = {_numbers(maneuver.dv)}    # {1e3 * np.linalg.norm(maneuver.dv):.3f} m/s")
    if error_model:
        lines.append(f'error_model = "{error_model}"')
    if maneuver.closed_loop:
        if navigation:
            lines.append(f'navigation = "{navigation}"')
        lines.append(f"target = {target}")
        lines.append(f"target_time = {maneuver.target_time!r}")
    lines.append("")
    return lines


def two_burn_example() -> str:
    mission, dynamics, info = cases.two_burn_transfer()
    engine = mission.maneuvers[0].error_model
    knowledge = mission.maneuvers[1].navigation
    lines = [
        "# Two-burn transfer from a 7000 km to a 12000 km circular orbit, with two statistical",
        "# corrections that target the arrival position.  This is validation test 3.",
        "#",
        "# Runs anywhere: the dynamics are the built-in two-body model, no GMAT needed.",
        "#",
        "#     gmat-uq run examples/two_burn_transfer.toml",
        "#",
        "# Generated by validation/make_examples.py.  Lengths in km, velocities in km/s, times in s.",
        "",
        "[dynamics]",
        'type = "two_body"',
        f"mu = {dynamics.mu!r}",
        "",
        "[mission]",
        f"initial_state = {_numbers(mission.initial_state)}    # circular, inclination 28.5 deg",
        f"final_time = {mission.final_time!r}    # arrival at apoapsis",
        'final_target = ["SMA", "INC", "RAAN"]',
        "",
        "[mission.initial_dispersion]",
        "sigmas = [0.2, 0.5, 0.2, 5e-4, 2e-4, 2e-4]    # radial, in-track, cross-track",
        'frame = "RIC"',
        "",
        *_error_model("Engine", engine),
        "[navigation.Tracking]",
        f"sigmas = {_numbers(np.sqrt(np.diag(knowledge.covariance)))}    # 50 m, 5 cm/s",
        "",
    ]
    for maneuver in mission.maneuvers:
        lines += _maneuver(maneuver, "Engine", "Tracking", '["X", "Y", "Z"]')
    lines += [
        "[analysis]",
        'methods = ["lincov", "sigma_point", "monte_carlo"]',
        "samples = 1000",
        "seed = 42",
        "workers = 4",
        'report = "two_burn_transfer_report.json"',
        "",
    ]
    return "\n".join(lines)


def lunar_example(gmat_root: str) -> str:
    mission, dynamics, info = cases.lunar_transfer(gmat_root)
    target = '{ parameters = ["BdotT", "BdotR", "RMAG"], body = "Luna" }'
    lines = [
        "# Translunar injection from a 185 km parking orbit to a lunar flyby, with three corrections",
        "# that hold the lunar B-plane and the distance to the Moon at a fixed arrival time.",
        "# This is validation test 4.  GMAT propagates everything, with the force model of",
        "# cislunar.script (Earth, Moon and Sun point masses).",
        "#",
        "#     set GMAT_ROOT=C:\\path\\to\\GMAT          (export GMAT_ROOT=... on Linux and macOS)",
        "#     gmat-uq run examples/lunar_flyby/lunar_flyby.toml",
        "#",
        f"# Epoch {info['epoch']}; flight time {info['flight_time_days']:.4f} days; perilune radius {info['perilune_radius_km']:.0f} km.",
        "# Generated by validation/make_examples.py.  Lengths in km, velocities in km/s, times in s.",
        "",
        "[dynamics]",
        'type = "gmat"',
        'script = "cislunar.script"',
        "",
        "[mission]",
        f"initial_state = {_numbers(mission.initial_state)}    # on the parking orbit",
        f"final_time = {mission.final_time!r}",
        'final_target = { parameters = ["BdotT", "BdotR"], body = "Luna" }',
        "",
        "[mission.initial_dispersion]",
        "sigmas = [0.5, 2.0, 0.5, 2e-3, 5e-4, 5e-4]    # radial, in-track, cross-track",
        'frame = "RIC"',
        "",
        *_error_model("UpperStage", mission.maneuvers[0].error_model),
        *_error_model("Thrusters", mission.maneuvers[1].error_model),
    ]
    for index, maneuver in enumerate(mission.maneuvers[1:], start=1):
        sigmas = np.sqrt(np.diag(maneuver.navigation.covariance))
        lines += [f"[navigation.Tracking{index}]", f"sigmas = {_numbers(sigmas)}", ""]
    lines += _maneuver(mission.maneuvers[0], "UpperStage", None, None)
    for index, maneuver in enumerate(mission.maneuvers[1:], start=1):
        lines += _maneuver(maneuver, "Thrusters", f"Tracking{index}", target)
    lines += [
        "[analysis]",
        'methods = ["lincov", "sigma_point", "monte_carlo"]',
        "samples = 500",
        "seed = 42",
        "workers = 4",
        'report = "lunar_flyby_report.json"',
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--gmat-root", default=os.environ.get("GMAT_ROOT"))
    options = parser.parse_args(argv)
    EXAMPLES.mkdir(exist_ok=True)
    (EXAMPLES / "two_burn_transfer.toml").write_text(two_burn_example(), encoding="utf-8")
    print("wrote examples/two_burn_transfer.toml")
    if options.gmat_root:
        folder = EXAMPLES / "lunar_flyby"
        folder.mkdir(exist_ok=True)
        (folder / "lunar_flyby.toml").write_text(lunar_example(options.gmat_root), encoding="utf-8")
        shutil.copyfile(cases.CISLUNAR_SCRIPT, folder / "cislunar.script")
        print("wrote examples/lunar_flyby/lunar_flyby.toml and cislunar.script")
    else:
        print("GMAT_ROOT not set: the lunar example was not regenerated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
